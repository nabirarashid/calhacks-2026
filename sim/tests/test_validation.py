"""sim/PHYSICS.md's validation table must stay true (W-B, PLAN.md v4 B5).

The table is generated by sim.validation, so it cannot be hand-edited out of sync. This
test makes sure that what it claims still holds: every validated row passes, and the
rejected rows still show why AeroBuildup and ControlSurface-VLM were rejected. If the
second ever stops being true (an AeroSandbox upgrade fixes it), the design decision should
be revisited, and this test is the prompt to do so.
"""
import pytest

pytest.importorskip("aerosandbox", reason="AeroSandbox is not installed")

from sim import validation   # noqa: E402


@pytest.mark.parametrize("row", validation.wing_rows() + validation.fin_rows(),
                         ids=lambda r: r[0])
def test_every_validated_row_passes(row):
    quantity, reference, result, verdict = row
    assert verdict == "pass", "%s vs %s: %s" % (quantity, reference, result)


def test_rejected_paths_are_still_wrong():
    rows = validation.rejected_rows()
    assert all(r[3] == "rejected" for r in rows)
    aerobuildup = rows[0][2]
    worst = float(aerobuildup.split("to x")[1].split()[0])
    assert worst > 1.2, "AeroBuildup camber error has closed (%s); revisit the lift path" % aerobuildup
    cls = rows[1][2].split("CL ")[1].split(" (")[0].split(" / ")
    assert len(set(cls)) == 1, "VLM now honours ControlSurface (%s); revisit the flap geometry" % cls


def test_markdown_renders():
    text = validation.markdown()
    assert text.count("| pass |") >= 11 and "| FAIL |" not in text
